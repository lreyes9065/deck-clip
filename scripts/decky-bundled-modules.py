#!/usr/bin/env python3
"""List the Python modules a Decky Loader release ships, for tests/decky_bundled_modules-<version>.txt.

Decky runs plugin backends on its own PyInstaller-frozen Python, which only
contains the stdlib modules Decky itself imports. Importing anything else from
a plugin raises ModuleNotFoundError and the plugin's backend never starts.

Usage (needs `pip install pyinstaller`):
    curl -LO https://github.com/SteamDeckHomebrew/decky-loader/releases/download/v3.3.0/PluginLoader
    python3 scripts/decky-bundled-modules.py PluginLoader v3.3.0 3.14.8 > tests/decky_bundled_modules-v3.3.0.txt

The third argument is the bundled Python version (PluginLoader's libpython,
e.g. 3.14.8 for v3.3.0 and 3.11.7 for v3.2.10). scripts/check-decky-imports.py
reads it from the header to pick the interpreter for the runtime import check.
Keep one list for the oldest and one for the newest Decky release supported.
"""

import io
import os
import sys
import tempfile
import zipfile

from PyInstaller.archive.readers import CArchiveReader, ZlibArchiveReader


def modules(binary: str) -> set[str]:
    archive = CArchiveReader(binary)
    found: set[str] = set()
    for name, entry in archive.toc.items():
        kind = entry[-1]
        if kind == "m":  # bootstrap modules stored in the executable itself
            found.add(name)
        elif name.endswith(".pyz") or kind == "z":
            with tempfile.NamedTemporaryFile(suffix=".pyz", delete=False) as handle:
                handle.write(archive.extract(name))
            try:
                found.update(ZlibArchiveReader(handle.name).toc)
            finally:
                os.unlink(handle.name)
        elif name == "base_library.zip":
            with zipfile.ZipFile(io.BytesIO(archive.extract(name))) as base:
                for member in base.namelist():
                    if member.endswith(".pyc"):
                        dotted = member[:-4].replace("/", ".")
                        found.add(dotted[:-9] if dotted.endswith(".__init__") else dotted)
        elif "/lib-dynload/" in name:
            found.add(name.rsplit("/", 1)[1].split(".", 1)[0])
    return found


if __name__ == "__main__":
    release = sys.argv[2] if len(sys.argv) > 2 else ""
    python = f" (Python {sys.argv[3]})" if len(sys.argv) > 3 else ""
    print(f"# Python modules shipped in Decky Loader {release} PluginLoader{python}.")
    print("# Generated by scripts/decky-bundled-modules.py. Plugin code may only import these")
    print("# (plus sys.builtin_module_names, which are compiled into the interpreter).")
    for name in sorted(modules(sys.argv[1])):
        print(name)
